// qrysmIndex is testdata/vectors/interchange/index.json.
type qrysmIndex struct {
	File                  string           `json:"file"`
	GenesisValidatorsRoot string           `json:"genesis_validators_root"`
	Validators            []qrysmValidator `json:"validators"`
}

type qrysmValidator struct {
	KeyIndex           int    `json:"key_index"`
	Pubkey             string `json:"pubkey"`
	SignedBlocks       int    `json:"signed_blocks"`
	SignedAttestations int    `json:"signed_attestations"`
}

// history is a file's records per public key, as comparable strings, whatever the file's layout.
func history(t *testing.T, file []byte) (string, map[string][]string) {
	t.Helper()
	var f struct {
		Metadata struct {
			GVR string `json:"genesis_validators_root"`
		} `json:"metadata"`
		Data []jEntry `json:"data"`
	}
	if err := json.Unmarshal(file, &f); err != nil {
		t.Fatal(err)
	}
	out := map[string][]string{}
	for _, e := range f.Data {
		var recs []string
		for _, b := range e.Blocks {
			recs = append(recs, "block "+b.Slot+" "+deref(b.Root))
		}
		for _, a := range e.Atts {
			recs = append(recs, "attestation "+a.Source+"/"+a.Target+" "+deref(a.Root))
		}
		slices.Sort(recs)
		out[strings.ToLower(e.Pubkey)] = recs
	}
	return strings.ToLower(f.Metadata.GVR), out
}

func deref(s *string) string {
	if s == nil {
		return "-"
	}
	return strings.ToLower(*s)
}

// The first half of the qrysm round trip (PLAN S8): the export qrysm's validator writes (generated by vectorgen)
// imports into either store without a failure, a conflict or a duplicate, and the signer's export of it holds the
// same history and re-imports to the same file. The second half, importing the signer's export back into qrysm,
// is TestQrysmInterchangeRoundTrip in test/acceptance, which runs vectorgen interchange-check.
func TestQrysmExportRoundTrip(t *testing.T) {
	var idx qrysmIndex
	vectors.Load(t, "interchange/index.json", &idx)
	file, err := os.ReadFile(filepath.Join(vectors.Dir(), "interchange", idx.File))
	must(t, err)
	wantGVR, want := history(t, file)
	if wantGVR != idx.GenesisValidatorsRoot || len(want) != len(idx.Validators) {
		t.Fatalf("the fixture and its index disagree: %s, %d validators", wantGVR, len(want))
	}
	forEachStore(t, func(t *testing.T, s slashing.Store) {
		res, err := interchange.Import(bg, s, bytes.NewReader(file), interchange.ImportOptions{})
		must(t, err)
		if len(res.Validators) != len(idx.Validators) || len(res.Failed()) != 0 {
			t.Fatalf("import: %+v", res)
		}
		for _, v := range res.Validators {
			i := slices.IndexFunc(idx.Validators, func(x qrysmValidator) bool { return strings.EqualFold(x.Pubkey, hx(v.PublicKey)) })
			if i < 0 {
				t.Fatalf("data[%d] has a key the index does not list", v.Index)
			}
			w := idx.Validators[i]
			if v.Blocks != (interchange.Counts{Imported: w.SignedBlocks}) ||
				v.Attestations != (interchange.Counts{Imported: w.SignedAttestations}) {
				t.Fatalf("key %d imported %+v and %+v, want %d blocks and %d attestations", w.KeyIndex, v.Blocks,
					v.Attestations, w.SignedBlocks, w.SignedAttestations)
			}
			st, err := s.ValidatorStatus(bg, slashing.KeyIDOf(v.PublicKey))
			if err != nil || !st.Enabled {
				t.Fatalf("key %d after the import: %+v %v", w.KeyIndex, st, err)
			}
		}

		var first bytes.Buffer
		_, err = interchange.Export(bg, s, &first, interchange.ExportOptions{})
		must(t, err)
		gotGVR, got := history(t, first.Bytes())
		if gotGVR != wantGVR || !maps.EqualFunc(got, want, slices.Equal) {
			t.Fatalf("the signer's export holds another history:\n%v\nwant\n%v", got, want)
		}

		again := memstoreOf(t)
		res, err = interchange.Import(bg, again, bytes.NewReader(first.Bytes()), interchange.ImportOptions{})
		if err != nil || len(res.Failed()) != 0 {
			t.Fatalf("re-import of the signer's export: %v %+v", err, res.Failed())
		}
		var second bytes.Buffer
		_, err = interchange.Export(bg, again, &second, interchange.ExportOptions{})
		must(t, err)
		if !bytes.Equal(first.Bytes(), second.Bytes()) {
			t.Fatalf("the re-imported export exports differently:\n%s\n---\n%s", first.Bytes(), second.Bytes())
		}
	})
}

func memstoreOf(t *testing.T) slashing.Store {
	t.Helper()
	s := stores[0].open(t)
	t.Cleanup(func() { _ = s.Close() })
	return s
}
