// formatVersion is bumped whenever the fixture layout changes.
const formatVersion = 1

// interopKeyCount is how many interop keys V4 lists: the e2e genesis size.
const interopKeyCount = 256

// generator holds what the fixture writers share.
type generator struct {
	repo    string // repository root
	vectors string // testdata/vectors under repo
	info    obj    // the generator record every file carries

	keys             []interopKey
	minimal, mainnet *chain
	genesis          state.BeaconState
	specSig          []byte
}

func (g *generator) chains() []*chain { return []*chain{g.minimal, g.mainnet} }

func (g *generator) chainByName(name string) (*chain, bool) {
	for _, c := range g.chains() {
		if c.def.name == name {
			return c, true
		}
	}
	return nil, false
}

// cc0 is the dedication every fixture file carries.
const cc0 = "Generated by tools/vectorgen; data only, dedicated to the public domain under CC0-1.0 " +
	"(https://creativecommons.org/publicdomain/zero/1.0/)."

func (g *generator) description(s string) string { return s + " " + cc0 }

// generatorInfo records the generator: the format version and the exact
// module versions of qrysm and the libraries it signs and hashes with, read
// from the build, so a fixture names the code that produced it. The Go
// version is left out on purpose: CI regenerates with several, and the
// fixtures must not differ.
func generatorInfo() (obj, error) {
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return nil, fmt.Errorf("no build info")
	}
	mods := obj{}
	for _, path := range []string{"github.com/theQRL/qrysm", "github.com/theQRL/go-qrl", "github.com/theQRL/go-qrllib", "github.com/prysmaticlabs/fastssz"} {
		for _, d := range bi.Deps {
			if d.Path != path {
				continue
			}
			v := d.Path + "@" + d.Version
			if d.Replace != nil {
				v = d.Replace.Path + "@" + d.Replace.Version
			}
			mods = mods.set(path, v)
		}
	}
	if len(mods) != 4 {
		return nil, fmt.Errorf("build info lacks a pinned module: %v", mods)
	}
	return obj{}.
		set("tool", "tools/vectorgen").
		set("format_version", formatVersion).
		set("modules", mods), nil
}

// generate writes every fixture under repo. It removes testdata/vectors
// first, so a fixture that is no longer generated does not linger.
func generate(repo string) error {
	if fieldparams.Preset != "mainnet" {
		return fmt.Errorf("vectorgen must be built without the minimal tag (preset %q)", fieldparams.Preset)
	}
	info, err := generatorInfo()
	if err != nil {
		return err
	}
	// qrysm's block generator logs at info level; keep the output to errors.
	logrus.SetLevel(logrus.WarnLevel)
	g := &generator{repo: repo, vectors: filepath.Join(repo, "testdata", "vectors"), info: info}
	if err := os.RemoveAll(g.vectors); err != nil {
		return err
	}
	if g.keys, err = loadKeys(interopKeyCount); err != nil {
		return err
	}
	for _, def := range networks {
		if def.preset == "" {
			continue
		}
		c, err := loadChain(def)
		if err != nil {
			return err
		}
		if def.preset == "minimal" {
			g.minimal = c
		} else {
			g.mainnet = c
		}
	}
	steps := []struct {
		name string
		fn   func(*generator) error
	}{
		{"networks", genNetworks},
		{"keys", genKeys},
		{"signing", genSigning},
		{"roots", genRoots},
		{"negative", genNegative},
		{"capabilities", genCapabilities},
		{"randao", genRandao},
		{"keystores", genKeystores},
		{"readme", genReadme},
	}
	for _, s := range steps {
		if err := s.fn(g); err != nil {
			return fmt.Errorf("%s: %w", s.name, err)
		}
	}
	return nil
}

// findRepo returns the repository root: the nearest directory above dir
// whose go.mod declares the signer module.
func findRepo(dir string) (string, error) {
	for d := dir; ; d = filepath.Dir(d) {
		b, err := os.ReadFile(filepath.Join(d, "go.mod"))
		if err == nil && strings.HasPrefix(string(b), "module github.com/rgeraldes24/go-remotesigner\n") {
			return d, nil
		}
		if filepath.Dir(d) == d {
			return "", fmt.Errorf("no go-remotesigner module above %s", dir)
		}
	}
}
