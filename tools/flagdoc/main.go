// Command flagdoc renders docs/reference/flags.md from the flag definitions
// in cmd/remotesigner/flags: every flag with its aliases, environment
// variables, config-file key, default and description.
//
// Usage:
//
//	go run ./tools/flagdoc [-o docs/reference/flags.md] [-check]
//
// With -check it writes nothing and fails when the file differs from what it
// would render; the flagdoc test runs the same comparison in CI.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/urfave/cli/v2"

	"github.com/rgeraldes24/go-remotesigner/cmd/remotesigner/flags"
)

func main() {
	out := flag.String("o", "docs/reference/flags.md", "output file")
	check := flag.Bool("check", false, "fail if the output file is stale instead of writing it")
	flag.Parse()

	want := render()
	if *check {
		got, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(got, want) {
			fmt.Fprintf(os.Stderr, "flagdoc: %s is stale; run `make docs`\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, want, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "flagdoc:", err)
		os.Exit(1)
	}
}

// render returns the Markdown reference.
func render() []byte {
	var b bytes.Buffer
	b.WriteString(`# Flag reference

<!-- Generated by tools/flagdoc from cmd/remotesigner/flags. Do not edit; run ` + "`make docs`" + `. -->

` + "```" + `
remotesigner [global flags] consensus [consensus flags]
remotesigner [global flags] consensus [consensus flags] migrate [migrate flags]
remotesigner [global flags] consensus [consensus flags] randao-state reset --key <id> [reset flags]
remotesigner [global flags] consensus [consensus flags] import --from <file> [import flags]
remotesigner [global flags] consensus [consensus flags] export --to <file> [--keys <id>,...] [export flags]
remotesigner [global flags] consensus [consensus flags] watermark-repair --epoch <epoch> --slot <slot> [repair flags]
remotesigner [global flags] consensus [consensus flags] set-high-watermark (--epoch <epoch> --slot <slot> | --remove) [flags]
remotesigner [global flags] consensus [consensus flags] disable-validator --key <id> [flags]
remotesigner [global flags] consensus keystore verify --file <keystore> --password-file <file>
remotesigner [global flags] consensus keystore verify --keystores-path <dir> (--keystores-password-file <file> | --keystores-passwords-path <dir>)
remotesigner --version
` + "```" + `

Every flag can also be set:

- in the environment, as ` + "`REMOTESIGNER_<NAME>`" + ` for a global flag and ` + "`REMOTESIGNER_CONSENSUS_<NAME>`" + ` for a
  consensus flag (the flag name or any alias in upper case, dashes as underscores);
- in the YAML file given by ` + "`--config-file`" + `, under its bare name or any of its aliases (the Config file column lists
  them all). Consensus flags may sit at the top level or in a ` + "`consensus:`" + ` section. A list flag takes a YAML list.
  Unknown keys are rejected, and so is a flag set under two of its names.

Precedence: command line, then environment, then config file, then default. Booleans are written ` + "`--flag`" + `,
` + "`--flag=true`" + ` or ` + "`--flag=false`" + `. ` + "`--flag false`" + ` does not work: the command-line parser (urfave/cli) reads
` + "`false`" + ` as an argument, which every command refuses as a usage error, so write ` + "`=`" + ` where Web3Signer takes the
value as the next argument (` + "`--slashing-protection-enabled=false`" + `). In the environment and the config file a
boolean takes a value, such as ` + "`true`" + ` or ` + "`false`" + `. Exit codes: 2 for usage errors (including a missing ` + "`--network`" + ` and an
invalid config file), 1 when the signer refuses to start or fails.

Signals: ` + "`SIGHUP`" + ` re-reads the token files, the TLS certificate and the client trust files
([` + "`../operations/tls.md`" + `](../operations/tls.md#5-rotating-tokens-and-certificates-with-sighup)); key files are
reloaded with ` + "`POST /reload`" + ` instead ([` + "`../operations/reload.md`" + `](../operations/reload.md#3-reload)).
` + "`SIGTERM`" + ` and ` + "`SIGINT`" + ` stop the signer: it stops accepting connections, lets in-flight requests finish for
up to 10 s, closes the store, wipes the keys and exits 0.
`)
	section(&b, "## Global flags", "", flags.Global(), false)
	section(&b, "## Consensus flags", flags.ConsensusCommand, flags.Consensus(), false)
	b.WriteString(`
## Store commands

These subcommands work on the slashing-protection store. A bbolt store they open while the signer is stopped (bbolt
allows one process per file; they refuse a store that a running signer holds). A Postgres database they use online,
under the advisory locks the signers take, so the signers keep running
([` + "`../operations/postgres.md`" + `](../operations/postgres.md)). They read ` + "`--data-path`" + ` for the default bbolt store
location. Their flags are not read from the config file; ` + "`--slashing-protection-db-url`" + `,
` + "`--slashing-protection-db-username`" + ` and ` + "`--slashing-protection-db-password-file`" + ` may also be given to
` + "`consensus`" + ` itself, on the command line, in the environment or in the config file. ` + "`import`" + `, ` + "`export`" + `
and ` + "`set-high-watermark`" + ` also read ` + "`--network`" + ` and its genesis flags from ` + "`consensus`" + `, for the
genesis validators root: ` + "`import`" + ` and ` + "`set-high-watermark`" + ` bind a store that has none to it, and ` + "`export`" + `
names it in the file of such a store. The history commands are described in
[` + "`../operations/migration.md`" + `](../operations/migration.md).
`)
	section(&b, "### consensus migrate", subcommand, flags.Migrate(), false)
	section(&b, "### consensus randao-state reset", subcommand, flags.RandaoStateReset(), false)
	section(&b, "### consensus import", subcommand, flags.Import(), false)
	section(&b, "### consensus export", subcommand, flags.Export(), false)
	section(&b, "### consensus watermark-repair", subcommand, flags.WatermarkRepair(), false)
	section(&b, "### consensus set-high-watermark", subcommand, flags.SetHighWatermark(), false)
	section(&b, "### consensus disable-validator", subcommand, flags.DisableValidatorFlags(), false)
	b.WriteString(`
` + "`consensus disable-validator`" + ` persists ` + "`enabled=false`" + ` for a key, which then gets 412
` + "`VALIDATOR_DISABLED`" + ` for blocks, attestations and new RANDAO layers. Reloads never disable a key. See
[` + "`../operations/reload.md`" + `](../operations/reload.md#5-disabling-a-validator).
`)
	b.WriteString(`
## Keystore commands

` + "`consensus keystore verify`" + ` decrypts one keystore with its password file (` + "`--file`" + `, ` + "`--password-file`" + `), or a
keystore directory as the signer loads it (` + "`--keystores-path`" + ` with ` + "`--keystores-password-file`" + ` or
` + "`--keystores-passwords-path`" + `), through the signer's keystore decryptor, policy and file-permission rule, and
checks that each keystore's pubkey is the key its seed derives. It prints each key's identifier and exits 0, or
names the refusals and exits 1. It needs no network, store or running signer. Its own flags read no environment
variables, so that a signer's ` + "`REMOTESIGNER_CONSENSUS_KEYSTORES_*`" + ` settings do not apply to it; the global
` + "`--strict-file-permissions`" + ` and ` + "`--signer-load-parallelism`" + ` do. See
[` + "`../operations/keystores.md`" + `](../operations/keystores.md).
`)
	section(&b, "### consensus keystore verify", subcommand, flags.KeystoreVerify(), false)
	b.WriteString(`
## Override flags

These flags are hidden from ` + "`--help`" + `. Each one lifts a startup refusal that protects a listener beyond loopback,
and accepts the risk that refusal guards against; on a loopback listener none of them is needed. They are set like
any other flag, on the command line, in the environment or in the config file. None of them can re-enable a
disabled slashing protection on such a listener: that refusal has no override. The container image, its entrypoint
and the examples in ` + "`deploy/`" + ` set none of them.
`)
	section(&b, "### Global", "", flags.Global(), true)
	section(&b, "### Consensus", flags.ConsensusCommand, flags.Consensus(), true)
	overrides(&b)
	return b.Bytes()
}

// overrides explains each hidden flag, in the order of the tables above.
func overrides(b *bytes.Buffer) {
	b.WriteString("\n### What each override accepts\n")
	doc := flags.Overrides()
	for _, f := range slices.Concat(flags.Global(), flags.Consensus()) {
		if !isHidden(f) {
			continue
		}
		o := doc[f.Names()[0]]
		fmt.Fprintf(b, "\n#### `--%s`\n\n", f.Names()[0])
		fmt.Fprintf(b, "- **Refused without it.** %s\n", markup(o.Refused))
		fmt.Fprintf(b, "- **The risk it accepts.** %s\n", markup(o.Risk))
		fmt.Fprintf(b, "- **Instead.** %s\n", markup(o.Instead))
	}
}

// flagName is a flag name in an override's explanation.
var flagName = regexp.MustCompile(`--[A-Za-z][A-Za-z0-9-]*(?:=[a-z0-9+]+)?`)

// markup sets the flag names of an explanation in code spans.
func markup(s string) string {
	return flagName.ReplaceAllStringFunc(s, func(n string) string { return "`" + n + "`" })
}

// subcommand marks a section of subcommand flags, which have no
// config-file key of their own.
const subcommand = "-"

func section(b *bytes.Buffer, title, command string, fs []cli.Flag, hidden bool) {
	fmt.Fprintf(b, "\n%s\n", title)
	b.WriteString("\n| Flag | Environment | Config file | Default | Description |\n|---|---|---|---|---|\n")
	for _, f := range fs {
		if isHidden(f) != hidden {
			continue
		}
		d := f.(cli.DocGenerationFlag)
		names := make([]string, 0, len(f.Names()))
		for _, n := range f.Names() {
			names = append(names, "`"+dashes(n)+n+"`")
		}
		env := make([]string, 0, len(d.GetEnvVars()))
		for _, e := range d.GetEnvVars() {
			env = append(env, "`"+e+"`")
		}
		yamlKey := configKeys(f.Names(), command)
		if command == subcommand {
			yamlKey = "none"
		}
		if len(env) == 0 {
			env = []string{"none"}
		}
		if f.Names()[0] == flags.ConfigFile {
			env, yamlKey = []string{"none"}, "none"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
			strings.Join(names, ", "), strings.Join(env, ", "), yamlKey, defaultOf(f), escape(d.GetUsage()))
	}
}

// configKeys renders the config-file keys of a flag with the given names:
// every name, as the YAML loader accepts each one, and for a flag of a
// command also each name in the command's section.
func configKeys(names []string, command string) string {
	keys := make([]string, 0, 2*len(names))
	for _, n := range names {
		keys = append(keys, "`"+n+"`")
	}
	if command != "" {
		for _, n := range names {
			keys = append(keys, "`"+command+"."+n+"`")
		}
	}
	if len(keys) == 1 {
		return keys[0]
	}
	return strings.Join(keys[:len(keys)-1], ", ") + " or " + keys[len(keys)-1]
}

func dashes(name string) string {
	if len(name) == 1 {
		return "-"
	}
	return "--"
}

func isHidden(f cli.Flag) bool {
	type hider interface{ IsVisible() bool }
	h, ok := f.(hider)
	return ok && !h.IsVisible()
}

// defaultOf renders a flag's default without urfave's quoting.
func defaultOf(f cli.Flag) string {
	d := f.(cli.DocGenerationFlag)
	var s string
	switch f := f.(type) {
	case *cli.StringSliceFlag:
		if f.Value != nil {
			s = strings.Join(f.Value.Value(), ",")
		}
	case *cli.BoolFlag:
		s = strconv.FormatBool(f.Value)
	default:
		s = d.GetDefaultText()
		if u, err := strconv.Unquote(s); err == nil {
			s = u
		}
	}
	if s == "" || s == "unset" {
		return "unset"
	}
	return "`" + s + "`"
}

// escape keeps Markdown from reading a description as a table cell break,
// emphasis or an HTML tag.
func escape(s string) string {
	return strings.NewReplacer("|", `\|`, "*", `\*`, "<", `\<`).Replace(s)
}
