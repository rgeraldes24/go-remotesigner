// Command flagdoc renders docs/reference/flags.md from the flag definitions
// in cmd/remotesigner/flags: every flag with its aliases, environment
// variables, config-file key, default and description.
//
// Usage:
//
//	go run ./tools/flagdoc [-o docs/reference/flags.md] [-check]
//
// With -check it writes nothing and fails when the file differs from what it
// would render; the flagdoc test runs the same comparison in CI.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strconv"
	"strings"

	"github.com/urfave/cli/v2"

	"github.com/rgeraldes24/go-remotesigner/cmd/remotesigner/flags"
)

func main() {
	out := flag.String("o", "docs/reference/flags.md", "output file")
	check := flag.Bool("check", false, "fail if the output file is stale instead of writing it")
	flag.Parse()

	want := render()
	if *check {
		got, err := os.ReadFile(*out)
		if err != nil || !bytes.Equal(got, want) {
			fmt.Fprintf(os.Stderr, "flagdoc: %s is stale; run `make docs`\n", *out)
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(*out, want, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "flagdoc:", err)
		os.Exit(1)
	}
}

// render returns the Markdown reference.
func render() []byte {
	var b bytes.Buffer
	b.WriteString(`# Flag reference

<!-- Generated by tools/flagdoc from cmd/remotesigner/flags. Do not edit; run ` + "`make docs`" + `. -->

` + "```" + `
remotesigner [global flags] consensus [consensus flags]
remotesigner [global flags] consensus [consensus flags] migrate [migrate flags]
remotesigner [global flags] consensus [consensus flags] randao-state reset --key <id> [reset flags]
remotesigner [global flags] consensus keystore verify --file <keystore> --password-file <file>
` + "```" + `

Every flag can also be set:

- in the environment, as ` + "`REMOTESIGNER_<NAME>`" + ` for a global flag and ` + "`REMOTESIGNER_CONSENSUS_<NAME>`" + ` for a
  consensus flag (the flag name or any alias in upper case, dashes as underscores);
- in the YAML file given by ` + "`--config-file`" + `, under its bare name. Consensus flags may sit at the top level or in a
  ` + "`consensus:`" + ` section. A list flag takes a YAML list. Unknown keys are rejected.

Precedence: command line, then environment, then config file, then default. Booleans are written ` + "`--flag`" + `,
` + "`--flag=true`" + ` or ` + "`--flag=false`" + `; ` + "`--flag false`" + ` does not work. Exit codes: 2 for usage errors (including a
missing ` + "`--network`" + ` and an invalid config file), 1 when the signer refuses to start or fails.
`)
	section(&b, "## Global flags", "", flags.Global(), false)
	section(&b, "## Consensus flags", flags.ConsensusCommand, flags.Consensus(), false)
	b.WriteString(`
## Offline store commands

These subcommands work on the bbolt slashing-protection store while the signer is stopped (bbolt allows one process
per file; they refuse a store that a running signer holds). They read ` + "`--data-path`" + ` for the default store
location. Their flags are not read from the config file; ` + "`--slashing-protection-db-url`" + ` may also be given to
` + "`consensus`" + ` itself, on the command line, in the environment or in the config file.
`)
	section(&b, "### consensus migrate", subcommand, flags.Migrate(), false)
	section(&b, "### consensus randao-state reset", subcommand, flags.RandaoStateReset(), false)
	b.WriteString(`
## Keystore commands

` + "`consensus keystore verify`" + ` decrypts one keystore with its password file through the signer's keystore
decryptor and policy, and checks that the keystore's pubkey is the key its seed derives. It prints the key's
identifier and exits 0, or names the refusal and exits 1. It needs no network, store or running signer. See
[` + "`../operations/keystores.md`" + `](../operations/keystores.md).
`)
	section(&b, "### consensus keystore verify", subcommand, flags.KeystoreVerify(), false)
	b.WriteString(`
## Override flags

These flags are hidden from ` + "`--help`" + `. Each one accepts a risk that a startup fail-safe otherwise refuses on a
non-loopback listener. None of them can re-enable a disabled slashing protection there: that refusal has no override.
`)
	section(&b, "### Global", "", flags.Global(), true)
	section(&b, "### Consensus", flags.ConsensusCommand, flags.Consensus(), true)
	return b.Bytes()
}

// subcommand marks a section of subcommand flags, which have no
// config-file key of their own.
const subcommand = "-"

func section(b *bytes.Buffer, title, command string, fs []cli.Flag, hidden bool) {
	fmt.Fprintf(b, "\n%s\n", title)
	b.WriteString("\n| Flag | Environment | Config file | Default | Description |\n|---|---|---|---|---|\n")
	for _, f := range fs {
		if isHidden(f) != hidden {
			continue
		}
		d := f.(cli.DocGenerationFlag)
		names := make([]string, 0, len(f.Names()))
		for _, n := range f.Names() {
			names = append(names, "`"+dashes(n)+n+"`")
		}
		env := make([]string, 0, len(d.GetEnvVars()))
		for _, e := range d.GetEnvVars() {
			env = append(env, "`"+e+"`")
		}
		yamlKey := "`" + f.Names()[0] + "`"
		switch {
		case command == subcommand:
			yamlKey = "none"
		case command != "":
			yamlKey = "`" + f.Names()[0] + "` or `" + command + "." + f.Names()[0] + "`"
		}
		if len(env) == 0 {
			env = []string{"none"}
		}
		if f.Names()[0] == flags.ConfigFile {
			env, yamlKey = []string{"none"}, "none"
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s | %s |\n",
			strings.Join(names, ", "), strings.Join(env, ", "), yamlKey, defaultOf(f), escape(d.GetUsage()))
	}
}

func dashes(name string) string {
	if len(name) == 1 {
		return "-"
	}
	return "--"
}

func isHidden(f cli.Flag) bool {
	type hider interface{ IsVisible() bool }
	h, ok := f.(hider)
	return ok && !h.IsVisible()
}

// defaultOf renders a flag's default without urfave's quoting.
func defaultOf(f cli.Flag) string {
	d := f.(cli.DocGenerationFlag)
	var s string
	switch f := f.(type) {
	case *cli.StringSliceFlag:
		s = strings.Join(f.Value.Value(), ",")
	case *cli.BoolFlag:
		s = strconv.FormatBool(f.Value)
	default:
		s = d.GetDefaultText()
		if u, err := strconv.Unquote(s); err == nil {
			s = u
		}
	}
	if s == "" || s == "unset" {
		return "unset"
	}
	return "`" + s + "`"
}

// escape keeps Markdown from reading a description as a table cell break,
// emphasis or an HTML tag.
func escape(s string) string {
	return strings.NewReplacer("|", `\|`, "*", `\*`, "<", `\<`).Replace(s)
}
